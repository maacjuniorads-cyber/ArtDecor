-- Temas (kits) -------------------------------------------------------
create table if not exists public.temas (
  id          text primary key,
  nome        text not null,
  cor         text not null,
  removido    boolean not null default false,
  criado_em   timestamptz not null default now()
);

-- Itens do estoque ---------------------------------------------------
create table if not exists public.itens (
  id                text primary key,
  nome              text not null,
  categoria         text not null,
  tema_id           text references public.temas (id),
  tipo              text not null check (tipo in ('varios', 'unica')),
  quantidade_total  integer check (quantidade_total is null or quantidade_total >= 0),  -- null = ainda não contado
  valor_aluguel     numeric(10, 2) not null default 0 check (valor_aluguel >= 0),
  foto_url          text,
  observacoes       text,
  removido          boolean not null default false,
  criado_em         timestamptz not null default now()
);

-- Clientes -----------------------------------------------------------
create table if not exists public.clientes (
  id          text primary key,
  nome        text not null,
  telefone    text not null,
  whatsapp    text,
  endereco    text,
  veiculo     jsonb,            -- { tipo, modelo, cor, placa } ou null (sem veículo)
  removido    boolean not null default false,
  importado   boolean not null default false,  -- veio da agenda do celular; falta completar o cadastro
  criado_em   timestamptz not null default now()
);

-- Pedidos ------------------------------------------------------------
-- Itens e pagamentos ficam dentro do pedido (jsonb): são sempre lidos e
-- gravados junto com ele, e assim cada gravação é uma operação só.
create table if not exists public.pedidos (
  id             text primary key,
  numero         integer generated by default as identity unique,  -- interno, só para ordenar
  codigo         text not null unique,          -- o que aparece no app: A13213 (gerado pelo banco)
  cliente_id     text not null references public.clientes (id),
  evento         text,
  tema_ids       text[] not null default '{}',
  itens          jsonb not null default '[]',   -- [{ itemId, quantidade, valorUnitario }]
  retirada       date not null,
  devolucao      date not null,
  status         text not null check (status in ('reservado', 'rua', 'devolvido', 'cancelado')),
  pagamentos     jsonb not null default '[]',   -- [{ id, valor, data, forma }]
  conferencia    jsonb,                          -- { data, por, problemas: [{ itemId, avariadas, faltando, obs, descontado }], observacao }
  cobrancas      jsonb not null default '[]',   -- [{ id, descricao, valor, itemId? }]
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  check (devolucao >= retirada)
);

create or replace function public.tocar_atualizado_em() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

drop trigger if exists pedidos_atualizado_em on public.pedidos;
create trigger pedidos_atualizado_em before update on public.pedidos
  for each row execute function public.tocar_atualizado_em();

-- Código do pedido: letra(s) + números aleatórios, 6 caracteres (A13213...).
-- A letra avança a cada 1000 pedidos; depois do Z vem AA1234, AB...
create or replace function public.gerar_codigo_pedido() returns trigger
language plpgsql as $$
declare
  bloco    int := (new.numero - 1) / 1000;  -- 0 = A, 1 = B, ...
  prefixo  text;
  digitos  int;
  tentativa text;
begin
  if new.codigo is not null then
    return new;  -- já tem (restauração de cópia, por exemplo)
  end if;

  if bloco < 26 then
    prefixo := chr(65 + bloco);                                        -- A..Z
  else
    prefixo := chr(65 + ((bloco - 26) / 26) % 26) || chr(65 + (bloco - 26) % 26);  -- AA..ZZ
  end if;
  digitos := 6 - length(prefixo);

  loop
    -- primeiro dígito nunca é zero (evita códigos tipo A00042)
    tentativa := prefixo || (floor(random() * 9 * 10 ^ (digitos - 1)) + 10 ^ (digitos - 1))::bigint::text;
    exit when not exists (select 1 from public.pedidos where codigo = tentativa);
  end loop;

  new.codigo := tentativa;
  return new;
end $$;

drop trigger if exists pedidos_codigo on public.pedidos;
create trigger pedidos_codigo before insert on public.pedidos
  for each row execute function public.gerar_codigo_pedido();

-- Acesso pela API: só o papel "authenticated" (usuário logado) ----------
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.temas, public.itens, public.clientes, public.pedidos to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on public.temas, public.itens, public.clientes, public.pedidos from anon;

-- Segurança: só usuários logados leem e gravam ------------------------
-- (O cadastro público de usuários deve ficar DESLIGADO no painel:
--  Authentication → Sign In / Providers → "Allow new users to sign up".)
alter table public.temas    enable row level security;
alter table public.itens    enable row level security;
alter table public.clientes enable row level security;
alter table public.pedidos  enable row level security;

drop policy if exists "equipe" on public.temas;
drop policy if exists "equipe" on public.itens;
drop policy if exists "equipe" on public.clientes;
drop policy if exists "equipe" on public.pedidos;
create policy "equipe" on public.temas    for all to authenticated using (true) with check (true);
create policy "equipe" on public.itens    for all to authenticated using (true) with check (true);
create policy "equipe" on public.clientes for all to authenticated using (true) with check (true);
create policy "equipe" on public.pedidos  for all to authenticated using (true) with check (true);

-- Tempo real: avisa o app quando algo muda ---------------------------
do $$
declare t text;
begin
  foreach t in array array['temas', 'itens', 'clientes', 'pedidos'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;

-- Fotos dos itens (Storage) ------------------------------------------
-- Bucket público para leitura (fotos de decoração, nomes aleatórios);
-- só usuários logados enviam, trocam ou apagam.
insert into storage.buckets (id, name, public)
values ('fotos', 'fotos', true)
on conflict (id) do nothing;

drop policy if exists "fotos: equipe consulta" on storage.objects;
drop policy if exists "fotos: equipe envia" on storage.objects;
drop policy if exists "fotos: equipe altera" on storage.objects;
drop policy if exists "fotos: equipe apaga" on storage.objects;
-- "consulta" é exigida pelo Storage ao enviar/substituir arquivos pela API.
create policy "fotos: equipe consulta" on storage.objects for select to authenticated using (bucket_id = 'fotos');
create policy "fotos: equipe envia"  on storage.objects for insert to authenticated with check (bucket_id = 'fotos');
create policy "fotos: equipe altera" on storage.objects for update to authenticated using (bucket_id = 'fotos');
create policy "fotos: equipe apaga"  on storage.objects for delete to authenticated using (bucket_id = 'fotos');
